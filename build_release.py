def research_to_repo():
    """The research behind the Oracle, for people to read and re-run: each topic's report (.md), its data (.json)
    and its scripts. Left out: cache/ folders (raw downloads: big, and other people's content) and run logs."""
    src, dst = os.path.join(HERE, 'research'), os.path.join(REPO_DIR, 'research')
    skip = shutil.ignore_patterns('cache', 'derived', '__pycache__', '*.pyc', '*_log*.txt', '*_out.txt', 'to_datapack.py',
                                  'add_browser_rates.py', 'series.json', 'analysis.json')
    shutil.copytree(src, dst, dirs_exist_ok=True, ignore=skip)
    # the researchers noted where they saved things on this PC: make those paths relative / generic
    local = re.compile(r'(?:file:)?[A-Za-z]:(?:\\\\|\\|/)+Home network(?:\\\\|\\|/)+poe2-toolkit(?:\\\\|\\|/)+', re.I)
    data = re.compile(r'[A-Za-z]:(?:\\\\|\\|/)+PoE2Toolkit', re.I)
    user = re.compile(r'[A-Za-z]:(?:\\\\|\\|/)+Users(?:\\\\|\\|/)+[^\\/"\'\s]+', re.I)
    for root, _, files in os.walk(dst):
        for f in files:
            if not f.endswith(('.md', '.json', '.py', '.txt')):
                continue
            fp = os.path.join(root, f)
            text = open(fp, encoding='utf-8', errors='replace').read()
            new_text = user.sub('<home>', data.sub('<data folder>', local.sub('', text)))
            if new_text != text:
                open(fp, 'w', encoding='utf-8', newline='\n').write(new_text)


def repo():
    """Refresh the GitHub working tree from the staged app + build files (keeps its .git folder)."""
    os.makedirs(REPO_DIR, exist_ok=True)
    for name in os.listdir(REPO_DIR):
        if name not in ('.git',):
            p = os.path.join(REPO_DIR, name)
            shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    shutil.copytree(os.path.join(STAGE, 'toolkit'), REPO_DIR, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('gameart'))   # the art ships in the installer only
    for f in REPO_EXTRA:
        shutil.copy2(os.path.join(HERE, f), REPO_DIR)
    os.makedirs(os.path.join(REPO_DIR, 'release'), exist_ok=True)
    for f in RELEASE_FILES:
        if os.path.exists(os.path.join(HERE, 'release', f)):
            shutil.copy2(os.path.join(HERE, 'release', f), os.path.join(REPO_DIR, 'release', f))
    research_to_repo()
    gh = os.path.join(HERE, 'release', 'github')
    if os.path.isdir(gh):   # README.md + docs/ for GitHub
        shutil.copytree(gh, REPO_DIR, dirs_exist_ok=True)
    # the same repository notes for every coding AI: Claude reads CLAUDE.md, Codex (ChatGPT) AGENTS.md, Gemini GEMINI.md
    cm = os.path.join(REPO_DIR, 'CLAUDE.md')
    if os.path.exists(cm):
        text = open(cm, encoding='utf-8').read()
        for name, who in (('AGENTS.md', 'Codex / ChatGPT'), ('GEMINI.md', 'Gemini')):
            body = text.replace('# Exile Oracle: notes for Claude working in this repository',
                                f'# Exile Oracle: notes for {who} working in this repository', 1)
            note = ('\n> The same notes are in CLAUDE.md, AGENTS.md and GEMINI.md (one per AI app); they are made from '
                    'CLAUDE.md by build_release.py.\n')
            open(os.path.join(REPO_DIR, name), 'w', encoding='utf-8').write(body.replace('\n', note, 1) if body.startswith('#') else body)
    open(os.path.join(REPO_DIR, '.gitignore'), 'w', encoding='utf-8').write(GITIGNORE)
    open(os.path.join(REPO_DIR, '.gitattributes'), 'w', encoding='utf-8').write(GITATTRIBUTES)
    soften_and_scan(REPO_DIR, skip_images=True)
    print('repo tree ready', REPO_DIR)


def gameart():
    """The game art as its own download for the Linux package (GitHub Actions adds it on a release):
    out/exile-oracle-gameart-<build>.tar.gz holding <build>/art-index.json + <build>/art/. Pictures only."""
    import tarfile
    src_root = os.path.join(STAGE, 'toolkit', 'gameart')
    builds = os.listdir(src_root) if os.path.isdir(src_root) else []
    if not builds:
        print('no game art staged (needs your own game-file extraction)')
        sys.exit(3)
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f'exile-oracle-gameart-{builds[0]}.tar.gz')
    with tarfile.open(path, 'w:gz', compresslevel=6) as t:
        t.add(os.path.join(src_root, builds[0]), arcname=builds[0])
    print('game art', path, f'{os.path.getsize(path) / 1e6:.0f} MB')


