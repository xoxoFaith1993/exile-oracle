TOOLS_START = '<!-- tools: generated by build_release.py from server.py, do not edit by hand -->'
TOOLS_END = '<!-- /tools -->'


def docs_check():
    """Players only see what the docs show (the author, 2026-11-21: "we cannot miss this stuff when uploading to GitHub").
    1. CLAUDE-GUIDE.md's tool list is written from server.py's TOOLS, so every tool is always in it.
    2. Every dashboard page (the sidebar) is named in README.md.
    3. Every research topic has a row in research/README.md.
    4. Every picture README.md shows exists.
    Any miss stops the build with a list of what to add."""
    sys.path.insert(0, HERE)
    import server
    gh = os.path.join(HERE, 'release', 'github')
    guide = os.path.join(gh, 'CLAUDE-GUIDE.md')
    g = open(guide, encoding='utf-8').read()
    rows = []
    for name, desc, _schema, _fn in server.TOOLS:
        first = re.split(r'(?<=[.:])\s', desc.strip(), 1)[0].rstrip(':')
        rows.append(f'| `{name}` | {first.replace("|", "/")} |')
    block = (TOOLS_START + '\n## Every tool the AI can use\nThe same tools work in Claude, ChatGPT / Codex and Gemini '
             'CLI.\n\n| Tool | What it does |\n|---|---|\n' + '\n'.join(rows) + '\n' + TOOLS_END)
    if TOOLS_START in g:
        g = g[:g.index(TOOLS_START)] + block + g[g.index(TOOLS_END) + len(TOOLS_END):]
    else:
        g = g.rstrip('\n') + '\n\n' + block + '\n'
    open(guide, 'w', encoding='utf-8', newline='\n').write(g)

    missing = []
    readme = open(os.path.join(gh, 'README.md'), encoding='utf-8').read()
    html = open(os.path.join(HERE, 'dashboard', 'index.html'), encoding='utf-8').read()
    nav = html[html.index('<nav id="nav">'):html.index('</nav>')]
    for label in re.findall(r'<button data-tab="[^"]+"[^>]*>([^<]+)<', nav):
        if label.strip().lower() not in readme.lower():
            missing.append(f'README.md: the "{label.strip()}" page')
    rr = open(os.path.join(HERE, 'research', 'README.md'), encoding='utf-8').read()
    for d in sorted(os.listdir(os.path.join(HERE, 'research'))):
        if os.path.isdir(os.path.join(HERE, 'research', d)) and not d.startswith(('_', '.')) and f'{d}/' not in rr:
            missing.append(f'research/README.md: a row for research/{d}')
    for img in re.findall(r'(docs/screenshots/[\w.-]+)', readme):
        if not os.path.exists(os.path.join(gh, img)):
            missing.append(f'release/github/{img} (README shows it; take it with release/readme_shots.py)')
    gal = os.path.join(gh, 'docs', 'GALLERY.md')   # every page in pictures: each picture must exist
    if os.path.exists(gal):
        for img in re.findall(r'(screenshots/[\w.-]+)', open(gal, encoding='utf-8').read()):
            if not os.path.exists(os.path.join(gh, 'docs', img)):
                missing.append(f'release/github/docs/{img} (the gallery shows it)')
    if missing:
        print('DOCS CHECK FAILED: players would miss these. Add them, then build again:')
        for m in missing:
            print('  -', m)
        sys.exit(1)
    print(f'docs check: {len(server.TOOLS)} tools in the guide, every page in the README, every research topic indexed')


DATA_VERSION_FILE = os.path.join(HERE, 'release', 'data_version.txt')


def data_version(bump=False):
    """Data versions are YYYY.MM.DD.N (N counts packs made that day). The last one made is in release/data_version.txt;
    bump=True makes the next one (for a new data pack)."""
    today = time.strftime('%Y.%m.%d')
    try:
        last = open(DATA_VERSION_FILE, encoding='utf-8').read().strip()
    except OSError:
        last = ''
    if not bump:
        return last or today + '.0'
    n = int(last.rsplit('.', 1)[1]) + 1 if last.startswith(today + '.') else 1
    ver = f'{today}.{n}'
    with open(DATA_VERSION_FILE, 'w', encoding='utf-8') as f:
        f.write(ver)
    return ver


def data_pack():
    """R27: a data-only pack (every datapack/*.json + manifest) for players' apps to pick up without a new release.
    Writes OUT/data/<version>/{manifest.json, exile-oracle-data-<version>.zip}. Publishing it needs the author's OK:
    the command to do it is printed, not run."""
    import zipfile
    from poe2kit import dataupdate
    src = os.path.join(HERE, 'datapack')
    for f in os.listdir(src):   # every file must be valid JSON before it goes out
        if f.endswith('.json'):
            json.load(open(os.path.join(src, f), encoding='utf-8'))
    ver = data_version(bump=True)
    man = dataupdate.make_manifest(src, ver, config.VERSION)
    d = os.path.join(OUT, 'data', ver)
    os.makedirs(d, exist_ok=True)
    zname = f'exile-oracle-data-{ver}.zip'
    zpath = os.path.join(d, zname)
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in man['files']:
            z.write(os.path.join(src, name), name)
        z.writestr('manifest.json', json.dumps(man, indent=1))
    man['zip'], man['zip_size'] = zname, os.path.getsize(zpath)
    with open(os.path.join(d, 'manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(man, f, indent=1)
    soften_and_scan(d, skip_images=True)
    print(f'data pack {ver}: {len(man["files"])} files, {man["zip_size"] // 1024} KB -> {d}')
    print('publish (with the author\'s OK):')
    print(f'  gh release create data-{ver} --prerelease --repo {config.REPO} --title "Data {ver}" '
          f'--notes "Data update (no new app): the app picks it up by itself." "{zpath}" "{os.path.join(d, "manifest.json")}"')
    return d


